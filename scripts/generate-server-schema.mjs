// Snapshots the server's shared-model schema into the app, so a brand-new local
// database gets every table on creation — even on a first launch with no network.
//
//   npm run schema:generate                 # uses EXPO_PUBLIC_API_URL from .env.local
//   npm run schema:generate -- <apiBaseUrl> # e.g. http://localhost:5221/api
//
// Source: GET {API}/Sync/schema (OSP-LIFEPLAN-OPERATION-API SyncController), which
// describes OneStPeterAPI/Shared/Models as mapped by AppDbContext. Re-run after the
// shared models change; tables/columns the snapshot misses are still added at
// runtime by schema.service.ts once the app reaches the server.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "src", "db", "server-schema.generated.ts");

function apiUrlFromEnv() {
  for (const file of [".env.local", ".env"]) {
    const path = join(root, file);
    if (!existsSync(path)) continue;
    const match = /^EXPO_PUBLIC_API_URL=(.+)$/m.exec(readFileSync(path, "utf8"));
    if (match) return match[1].trim();
  }
  return null;
}

const apiUrl = (process.argv[2] ?? apiUrlFromEnv() ?? "").replace(/\/+$/, "");
if (!apiUrl) {
  console.error("No API URL: pass one, or set EXPO_PUBLIC_API_URL in .env.local");
  process.exit(1);
}

const res = await fetch(`${apiUrl}/Sync/schema`);
if (!res.ok) {
  console.error(`GET ${apiUrl}/Sync/schema failed: ${res.status} ${res.statusText}`);
  process.exit(1);
}
const schema = await res.json();
if (typeof schema.version !== "string" || !Array.isArray(schema.tables)) {
  console.error("Unexpected response shape:", JSON.stringify(schema).slice(0, 200));
  process.exit(1);
}

const banner = `// GENERATED by scripts/generate-server-schema.mjs — do not edit by hand.
// Snapshot of GET ${apiUrl}/Sync/schema, taken ${new Date().toISOString()}.
// Re-generate with: npm run schema:generate
`;
const body = `import type { ServerSchema } from "@/services/schema.service";

export const BUNDLED_SERVER_SCHEMA: ServerSchema = ${JSON.stringify(schema, null, 2)};
`;
writeFileSync(outFile, banner + "\n" + body);

console.log(
  `Wrote ${schema.tables.length} tables (schema ${schema.version}) to ${outFile.slice(root.length + 1)}`,
);
